import React, { useState, useCallback, useEffect, useRef } from 'react';
import { useOS } from '../context/OSContext';
import { hogwartsGenerate } from '../utils/hogwartsGenerate';
import {
  HOUSE_META, awardHousePoints,
  FORUM_BOARDS, FORUM_NPC_POOL, FORUM_ERAS,
  forumTimeContext, forumEraInstruction,
  shouldAutoGenerateForumPosts, markForumAutoGenerated,
  loadForumPosts, saveForumPosts, parseForumGeneration,
  loadForumEra, saveForumEra,
} from '../utils/hogwarts';
import type { HouseId, SocialPost } from '../types';

// 兼容旧数据：老帖子的 board 存的是版块名，统一迁到 id。
const NAME_TO_BOARD_ID = new Map(FORUM_BOARDS.filter(b => b.id !== 'all').map(b => [b.name, b.id]));
const normalizeBoardId = (p: any): string => {
  if (p?.board && FORUM_BOARDS.some(b => b.id === p.board)) return p.board;
  const byName = NAME_TO_BOARD_ID.get(p?.board);
  if (byName) return byName;
  return 'great-hall';
};

function loadPosts(): SocialPost[] {
  return loadForumPosts().map(p => ({ ...p, board: normalizeBoardId(p) })) as SocialPost[];
}

function savePosts(posts: SocialPost[]) {
  saveForumPosts(posts as unknown as Array<Record<string, any>>);
}

interface DraftPost {
  post: SocialPost;
  houseId?: HouseId;
}

const ForumApp: React.FC = () => {
  const { closeApp, characters, apiConfig, userProfile, addToast } = useOS();
  const [posts, setPosts] = useState<SocialPost[]>(() => loadPosts());
  const [board, setBoard] = useState('all');
  const [composing, setComposing] = useState(false);
  const [title, setTitle] = useState('');
  const [content, setContent] = useState('');
  const [busy, setBusy] = useState(false);
  const [openPost, setOpenPost] = useState<SocialPost | null>(null);
  const [era, setEra] = useState(() => loadForumEra());
  const autoStarted = useRef(false);

  const persist = (p: SocialPost[]) => { savePosts(p); setPosts(p); };

  const filtered = board === 'all' ? posts : posts.filter(p => p.board === board);

  // ── 发帖核心：角色 / NPC / 用户共用 ─────────────────────────────
  const buildPost = useCallback((opts: {
    authorName: string; authorAvatar?: string;
    title: string; content: string;
    boardId: string; authorType: SocialPost['authorType'];
    authorCharId?: string; houseId?: HouseId; likes?: number;
  }, now = Date.now()): SocialPost => ({
    id: `post-${now}-${Math.random().toString(36).slice(2, 6)}`,
    authorName: opts.authorName,
    authorAvatar: opts.authorAvatar || '',
    title: opts.title, content: opts.content,
    images: [], likes: opts.likes ?? 0, isCollected: false, isLiked: false,
    comments: [], timestamp: now, tags: [],
    authorType: opts.authorType,
    ...(opts.authorCharId ? { authorCharId: opts.authorCharId } : {}),
    board: opts.boardId,
    houseId: opts.houseId,
  }), []);

  const generateOne = useCallback(async (opts: {
    name: string; avatar?: string; houseId?: HouseId;
    charId?: string; persona?: string; authorType: SocialPost['authorType'];
    postsSnapshot: SocialPost[];
  }): Promise<DraftPost> => {
    const ctx = forumTimeContext();
    const eraLabel = FORUM_ERAS.find(e => e.id === era)?.label;
    const houseHint = opts.houseId ? `，并体现${HOUSE_META[opts.houseId].cn}学院特色` : '';
    const personaHint = opts.persona ? `（性格：${opts.persona}）` : '';
    const charHint = `你是霍格沃茨${opts.houseId ? HOUSE_META[opts.houseId].cn : ''}的学生 ${opts.name}${personaHint}${houseHint}。`;
    const instruction = `你在霍格沃茨校内论坛「猫头鹰邮报」发一条帖子，以第一人称、符合身份和性格的口吻写。\n${forumEraInstruction(ctx, charHint, era)}\n严格输出 JSON：{"title":"帖子标题","content":"正文，80-200字"}`;
    const result = await hogwartsGenerate({
      feature: 'forum', globalApi: apiConfig as any,
      ...(opts.charId ? { char: characters.find(c => c.id === opts.charId) } : {}),
      userProfile: userProfile as any,
      instructions: instruction,
      userInput: `以 ${opts.name} 的身份${eraLabel ? `在「${eraLabel}」背景下` : `发一条${ctx.periodLabel}的`}帖子`,
      maxTokens: 700,
    });
    const parsed = parseForumGeneration(result);
    const boardMeta = FORUM_BOARDS.find(b => b.id === (opts.houseId ? opts.houseId : ['great-hall', 'library', 'great-hall'][Math.floor(Math.random() * 3)])) || FORUM_BOARDS[1];
    const post = buildPost({
      authorName: opts.name,
      authorAvatar: opts.avatar,
      title: parsed.title,
      content: parsed.content,
      boardId: boardMeta.id,
      authorType: opts.authorType,
      ...(opts.charId ? { authorCharId: opts.charId } : {}),
      houseId: opts.houseId,
      likes: Math.floor(Math.random() * 25),
    });
    return { post, houseId: opts.houseId };
  }, [apiConfig, characters, userProfile, buildPost, era]);

  // ── 进入论坛自动补帖：按当前时代生成 NPC + 角色发帖 ───────────────
  useEffect(() => {
    if (autoStarted.current) return;
    autoStarted.current = true;
    const current = loadPosts();
    if (!shouldAutoGenerateForumPosts(current.length)) return;
    let cancelled = false;
    (async () => {
      try {
        markForumAutoGenerated();
        // 一次生成 5-6 条：用户角色最多 2 条 + NPC 补足；没角色则全 NPC。
        const batch = 5 + Math.floor(Math.random() * 2);
        const charPool = characters.slice();
        const shuffledNpc = [...FORUM_NPC_POOL].sort(() => Math.random() - 0.5);
        const tasks: Array<Parameters<typeof generateOne>[0]> = [];
        for (const c of [...charPool].sort(() => Math.random() - 0.5).slice(0, Math.min(2, charPool.length))) {
          tasks.push({
            name: c.name, avatar: (c as any).avatar, houseId: (c as any).houseId,
            charId: c.id, authorType: 'character', postsSnapshot: current,
          });
        }
        for (const npc of shuffledNpc.slice(0, batch - tasks.length)) {
          tasks.push({ name: npc.name, houseId: npc.houseId, persona: npc.persona, authorType: 'stranger', postsSnapshot: current });
        }
        const results = await Promise.allSettled(tasks.map(t => generateOne(t)));
        if (cancelled) return;
        const fresh: SocialPost[] = [];
        let earned: Array<[HouseId, string]> = [];
        for (const r of results) {
          if (r.status === 'fulfilled') {
            fresh.push(r.value.post);
            if (r.value.houseId) earned.push([r.value.houseId, r.value.post.authorName]);
          }
        }
        if (fresh.length > 0) {
          const base = loadPosts().map(p => ({ ...p, board: normalizeBoardId(p) })) as SocialPost[];
          persist([...fresh, ...base]);
          for (const [hid, name] of earned) awardHousePoints(hid, 2, `${name} 在论坛活跃发言`);
          addToast(`🦉 ${fresh.length} 位霍格沃茨学生刚刚发了新帖`, 'success');
        }
      } catch { /* 静默失败：论坛仍是空态可手动生成 */ }
    })();
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const handlePublish = () => {
    if (!title.trim() || !content.trim()) { addToast('请填写标题和内容', 'error'); return; }
    const boardMeta = FORUM_BOARDS.find(b => b.id === board);
    const post = buildPost({
      authorName: userProfile.name || '我',
      authorAvatar: (userProfile as any).avatar || '',
      title: title.trim(), content: content.trim(),
      boardId: boardMeta?.id || 'great-hall',
      authorType: 'user',
      houseId: boardMeta?.house,
    });
    persist([post, ...posts]);
    setTitle(''); setContent(''); setComposing(false);
    addToast('发帖成功', 'success');
  };

  const handleGenerate = async () => {
    if (busy) return;
    setBusy(true);
    try {
      // 一次生成 5-6 篇：优先角色（最多 2 条），其余由 NPC 补足。
      const batch = 5 + Math.floor(Math.random() * 2);
      const shuffledNpc = [...FORUM_NPC_POOL].sort(() => Math.random() - 0.5);
      const charShuffled = [...characters].sort(() => Math.random() - 0.5);
      const tasks: Array<Parameters<typeof generateOne>[0]> = charShuffled.slice(0, Math.min(2, charShuffled.length))
        .map(c => ({
          name: c.name, avatar: (c as any).avatar, houseId: (c as any).houseId,
          charId: c.id, authorType: 'character' as const, postsSnapshot: posts,
        }));
      for (const npc of shuffledNpc.slice(0, batch - tasks.length)) {
        tasks.push({ name: npc.name, houseId: npc.houseId, persona: npc.persona, authorType: 'stranger' as const, postsSnapshot: posts });
      }
      const results = await Promise.allSettled(tasks.map(t => generateOne(t)));
      const fresh: SocialPost[] = [];
      const earned: Array<[HouseId, string]> = [];
      for (const r of results) {
        if (r.status === 'fulfilled') {
          fresh.push(r.value.post);
          if (r.value.houseId) earned.push([r.value.houseId, r.value.post.authorName]);
        }
      }
      if (fresh.length === 0) throw new Error('这一批都没生成成功，稍后再试');
      persist([...fresh, ...posts]);
      for (const [hid, name] of earned) awardHousePoints(hid, 2, `${name} 在论坛活跃发言`);
      addToast(`🦉 ${fresh.length} 位霍格沃茨学生刚刚发了新帖`, 'success');
    } catch (e: any) {
      addToast(e?.message || '生成失败', 'error');
    } finally { setBusy(false); }
  };

  const handleLike = (id: string) => {
    const next = posts.map(p => p.id === id ? { ...p, isLiked: !p.isLiked, likes: p.likes + (p.isLiked ? -1 : 1) } : p);
    persist(next);
    if (openPost?.id === id) setOpenPost(next.find(p => p.id === id) || null);
  };

  const renderAvatar = (post: SocialPost, size = 'w-8 h-8') => {
    if (post.authorAvatar) return <img src={post.authorAvatar} alt="" className={`${size} rounded-full object-cover bg-stone-200`} />;
    return (
      <div className={`${size} rounded-full flex items-center justify-center text-xs font-bold text-white shrink-0`}
        style={{ background: post.houseId ? HOUSE_META[post.houseId].color : '#64748b' }}>
        {(post.authorName || '?')[0]}
      </div>
    );
  };

  return (
    <div className="h-full w-full bg-emerald-50 flex flex-col font-light overflow-hidden">
      <div className="bg-[#0e1a40]/85 backdrop-blur-md border-b border-amber-200/20 shrink-0 sticky top-0 z-10" style={{ paddingTop: 'var(--safe-top)' }}>
        <div className="flex items-center px-4 py-3 gap-2">
          <button onClick={closeApp} className="p-2 -ml-2 rounded-full hover:bg-white/10 active:scale-90 transition-transform">
            <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" className="w-6 h-6 text-amber-200">
              <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 19.5 8.25 12l7.5-7.5" />
            </svg>
          </button>
          <h1 className="text-xl font-medium text-amber-100 tracking-wide flex-1">🦉 猫头鹰论坛</h1>
          <select value={era} onChange={e => { const v = e.target.value; setEra(v); saveForumEra(v); }}
            className="px-2 py-1.5 rounded-full bg-white/10 text-amber-200/80 text-xs border border-amber-200/20 focus:outline-none max-w-[9.5rem]"
            title="选择论坛时间线时代">
            {FORUM_ERAS.map(e => <option key={e.id} value={e.id} className="text-stone-800">{e.label}</option>)}
          </select>
          <button onClick={handleGenerate} disabled={busy} className="px-3 py-1.5 rounded-full bg-amber-300/90 text-[#0e1a40] text-xs font-medium disabled:opacity-50">
            {busy ? '生成中…' : '✨ 生成一批'}
          </button>
        </div>
        <div className="flex gap-2 px-4 pb-3 overflow-x-auto no-scrollbar">
          {FORUM_BOARDS.map(b => (
            <button key={b.id} onClick={() => setBoard(b.id)}
              className={`shrink-0 px-3 py-1.5 rounded-full text-sm ${board === b.id ? 'bg-amber-300 text-[#0e1a40] font-medium' : 'text-amber-200/80 bg-white/10'}`}>
              {b.name}
            </button>
          ))}
        </div>
      </div>

      <div className="flex-1 overflow-y-auto px-4 py-4 pb-24">
        {filtered.length === 0 ? (
          <div className="text-center py-16 text-stone-400">
            <div className="text-5xl mb-4">🦉</div>
            <p className="text-sm">这个版块还没人发言。</p>
            <p className="text-xs mt-2">点右上角「生成一批」，或稍等猫头鹰送达新帖。</p>
          </div>
        ) : (
          <div className="space-y-3">
            {filtered.map(post => (
              <div key={post.id} onClick={() => setOpenPost(post)}
                className="rounded-2xl bg-white/90 backdrop-blur p-4 shadow-sm border border-emerald-100 active:scale-[0.99] transition-transform">
                <div className="flex items-center gap-2 mb-2">
                  {renderAvatar(post)}
                  <div className="flex-1 min-w-0">
                    <div className="text-sm font-medium text-stone-700 truncate">
                      {post.authorName}
                      {post.authorType === 'stranger' && <span className="ml-1 text-[9px] px-1 py-px rounded bg-indigo-100 text-indigo-500">NPC</span>}
                      {post.authorType === 'character' && <span className="ml-1 text-[9px] px-1 py-px rounded bg-emerald-100 text-emerald-600">角色</span>}
                    </div>
                    <div className="text-xs text-stone-400">
                      {FORUM_BOARDS.find(b => b.id === post.board)?.name || '校园'} · {new Date(post.timestamp).toLocaleString('zh-CN', { month: 'numeric', day: 'numeric', hour: '2-digit', minute: '2-digit' })}
                    </div>
                  </div>
                  {post.houseId && (
                    <span className="px-2 py-0.5 rounded-full text-xs text-white" style={{ background: HOUSE_META[post.houseId].color }}>
                      {HOUSE_META[post.houseId].cn}
                    </span>
                  )}
                </div>
                <h3 className="font-semibold text-stone-800 mb-1">{post.title}</h3>
                <p className="text-sm text-stone-600 line-clamp-3 whitespace-pre-wrap">{post.content}</p>
                <div className="mt-3 flex items-center gap-4 text-xs text-stone-400">
                  <button onClick={e => { e.stopPropagation(); handleLike(post.id); }} className={post.isLiked ? 'text-rose-500' : ''}>
                    {post.isLiked ? '❤️' : '🤍'} {post.likes}
                  </button>
                  <span>💬 {post.comments.length}</span>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>

      <button onClick={() => setComposing(true)}
        className="absolute bottom-5 right-5 w-14 h-14 rounded-full bg-amber-500 text-white text-3xl shadow-lg active:scale-90 transition-transform flex items-center justify-center">
        ✎
      </button>

      {composing && (
        <div className="absolute inset-0 z-20 flex flex-col bg-white">
          <div className="flex items-center px-4 py-3 gap-2 border-b" style={{ paddingTop: 'var(--safe-top)' }}>
            <button onClick={() => setComposing(false)} className="text-stone-500 text-sm">取消</button>
            <h2 className="flex-1 text-center font-medium text-stone-700">发新帖</h2>
            <button onClick={handlePublish} className="text-amber-600 text-sm font-medium">发布</button>
          </div>
          <div className="p-4 space-y-3">
            <select value={board} onChange={e => setBoard(e.target.value)} className="w-full px-3 py-2 rounded-xl bg-stone-100 text-sm">
              {FORUM_BOARDS.filter(b => b.id !== 'all').map(b => <option key={b.id} value={b.id}>{b.name}</option>)}
            </select>
            <input value={title} onChange={e => setTitle(e.target.value)} placeholder="标题"
              className="w-full px-3 py-3 rounded-xl bg-stone-100 text-lg font-medium focus:outline-none" />
            <textarea value={content} onChange={e => setContent(e.target.value)} placeholder="写下你想说的…" rows={10}
              className="w-full px-3 py-3 rounded-xl bg-stone-100 focus:outline-none resize-none" />
          </div>
        </div>
      )}

      {openPost && (
        <div className="absolute inset-0 z-20 flex flex-col bg-white" onClick={() => setOpenPost(null)}>
          <div className="flex items-center px-4 py-3 gap-2 border-b" style={{ paddingTop: 'var(--safe-top)' }} onClick={e => e.stopPropagation()}>
            <button onClick={() => setOpenPost(null)} className="p-2 -ml-2">
              <svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" strokeWidth={1.5} stroke="currentColor" className="w-6 h-6 text-stone-600">
                <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 19.5 8.25 12l7.5-7.5" />
              </svg>
            </button>
            <h2 className="font-medium text-stone-700">帖子详情</h2>
          </div>
          <div className="p-4 overflow-y-auto" onClick={e => e.stopPropagation()}>
            <div className="flex items-center gap-2 mb-3">
              {renderAvatar(openPost, 'w-10 h-10')}
              <div>
                <div className="text-sm font-medium text-stone-700">{openPost.authorName}</div>
                <div className="text-xs text-stone-400">{new Date(openPost.timestamp).toLocaleString('zh-CN')}</div>
              </div>
            </div>
            <h1 className="text-xl font-bold text-stone-800 mb-3">{openPost.title}</h1>
            <p className="text-sm text-stone-700 whitespace-pre-wrap leading-relaxed">{openPost.content}</p>
            <button onClick={() => handleLike(openPost.id)} className={`mt-6 px-4 py-2 rounded-full ${openPost.isLiked ? 'bg-rose-100 text-rose-600' : 'bg-stone-100 text-stone-500'}`}>
              {openPost.isLiked ? '❤️ 已点赞' : '🤍 点赞'} · {openPost.likes}
            </button>
          </div>
        </div>
      )}
    </div>
  );
};

export default ForumApp;
